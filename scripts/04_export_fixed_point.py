"""Stage 4: export trained logistic regression to bit-accurate fixed-point RTL.

Train using scripts/03_train_compare.py first. Only TRAIN and VALIDATION
rows are used; the held-out TEST partition is not inspected.
"""
import argparse
import csv
import json
import math
import subprocess
import sys
from pathlib import Path

import joblib
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.fixed_point import make_fixed_model, quantize, quantized_linear_predict, to_twos_hex
from src.secom_io import load_secom


def signed_hex(val, bits):
    return f"{bits}'sh{to_twos_hex(val, bits)}"


def load_indices(path, n):
    groups = {'train': [], 'validation': [], 'test': []}
    seen = set()
    with open(path, newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            i = int(row['row_index'])
            if i in seen or i < 0 or i >= n or row['split'] not in groups:
                raise ValueError('invalid saved split assignments')
            seen.add(i)
            groups[row['split']].append(i)
    if len(seen) != n:
        raise ValueError('saved splits do not cover dataset')
    return groups


def write_rtl_constants(folder, spec):
    bits, weights = spec['bits'], spec['weights']
    lines = [f'// Autogenerated; {len(weights)} weights, signed {bits}-bit',
             f'localparam signed [63:0] OFFSET = {signed_hex(spec["offset"], 64)};',
             f'function automatic signed [BITS-1:0] weight_at(input integer index);',
             '    begin', '        case (index)']
    for i, w in enumerate(weights):
        lines.append(f'            {i}: weight_at = {signed_hex(w, bits)};')
    lines.extend(["            default: weight_at = '0;", '        endcase', '    end', 'endfunction'])
    (folder / 'model_constants.svh').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def write_vectors(folder, xint, predictions, bits):
    # Packed feature zero at LSB, expected prediction at MSB.
    with (folder / 'vectors.mem').open('w', encoding='ascii') as f:
        for row, pred in zip(xint, predictions):
            packed = sum((int(x) & ((1 << bits) - 1)) << (i * bits) for i, x in enumerate(row))
            packed |= int(pred) << (len(row) * bits)
            f.write(f'{packed:0{((len(row) * bits + 1) + 3) // 4}x}\n')


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--features', type=int, default=16, choices=(8, 16, 32))
    p.add_argument('--bits', nargs='+', type=int, default=[8, 12, 16], choices=(8, 12, 16))
    p.add_argument('--simulate', action='store_true', help='run iverilog and vvp for each precision')
    args = p.parse_args()

    model_file = ROOT / 'artifacts' / f'step3_logistic_k{args.features:02d}.joblib'
    if not model_file.exists():
        p.error(f'{model_file} missing: run python scripts/03_train_compare.py first')
    bundle = joblib.load(model_file)  # only load trusted, locally generated artifacts
    X, y, _ = load_secom(ROOT / 'data/raw/secom.zip')
    split = load_indices(ROOT / 'reports/split_assignments.csv', len(X))
    train = bundle['preprocessor'].transform(X.iloc[split['train']])
    val = bundle['preprocessor'].transform(X.iloc[split['validation']])
    yval = y.iloc[split['validation']].to_numpy()
    model = bundle['model']
    threshold = float(bundle['threshold'])
    fp_pred = model.predict_proba(val)[:, 1] >= threshold
    out_root = ROOT / 'hardware' / 'generated'
    out_root.mkdir(parents=True, exist_ok=True)
    results = []
    for bits in args.bits:
        spec = make_fixed_model(model, train, bits, threshold)
        folder = out_root / f'k{args.features:02d}_b{bits:02d}'
        folder.mkdir(exist_ok=True)
        x_int = quantize(val, bits, spec['xfrac'])
        fixed_pred = quantized_linear_predict(x_int, spec['weights'], spec['offset'])
        write_rtl_constants(folder, spec)
        write_vectors(folder, x_int, fixed_pred, bits)
        (folder / 'config.json').write_text(json.dumps({**spec, 'features': bundle['selected_features'], 'validation_size': len(val)}, indent=2), encoding='utf-8')
        tp = int(np.sum(fixed_pred & (yval == 1)))
        fn = int(np.sum(~fixed_pred & (yval == 1)))
        fp = int(np.sum(fixed_pred & (yval == 0)))
        tn = int(np.sum(~fixed_pred & (yval == 0)))
        result = dict(features=args.features, bits=bits, input_fractional_bits=spec['xfrac'], weight_fractional_bits=spec['wfrac'], validation_samples=len(val), agreement_with_float=float(np.mean(fp_pred == fixed_pred)), tp=tp, fn=fn, fp=fp, tn=tn, recall=tp/(tp+fn), false_positive_rate=fp/(fp+tn), screening_cost=10*fn+fp, rtl_simulation='not_run')
        if args.simulate:
            cmd = ['iverilog', '-g2012', '-s', 'classifier_tb', f'-DBITS={bits}', f'-DN={args.features}', f'-DSAMPLES={len(val)}', '-I', str(folder), '-o', 'classifier_sim', str(ROOT/'hardware/linear_classifier.sv'), str(ROOT/'hardware/classifier_tb.sv')]
            subprocess.run(cmd, cwd=folder, check=True)
            run = subprocess.run(['vvp', 'classifier_sim'], cwd=folder, check=True, capture_output=True, text=True)
            print(run.stdout.strip())
            result['rtl_simulation'] = 'passed'
        results.append(result)
        print(f"{bits:2d}-bit: agreement={result['agreement_with_float']:.3f}, recall={result['recall']:.3f}, cost={result['screening_cost']}")
    import pandas as pd
    pd.DataFrame(results).to_csv(ROOT/'reports/step4_quantization.csv', index=False)
    print(f'Saved: {out_root} and reports/step4_quantization.csv')
    print('TEST partition was NOT evaluated. Synthesized area/timing not measured.')


if __name__ == '__main__':
    main()
